function text(languageCode, key) {
    var details = DETAIL_LABELS[language(languageCode)]
    if (details[key]) return details[key]
    var controls = CONTROL_LABELS[language(languageCode)]
    if (controls[key]) return controls[key]
    var local = catalog(languageCode)
    if (local[key]) {
        return local[key]
    }
    if (EN[key]) {
        return EN[key]
    }
    return key
}

function weather(languageCode, key, fallback) {
    var local = weatherCatalog(languageCode)
    var raw = String(key || "unknown").toLowerCase()
    if (local[raw]) {
        return local[raw]
    }
    if (WEATHER_EN[raw]) {
        return WEATHER_EN[raw]
    }
    return fallback || text(languageCode, "unknown")
}
