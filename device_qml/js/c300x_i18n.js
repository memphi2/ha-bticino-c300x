function language(languageCode) {
    var raw = String(languageCode || "en").toLowerCase()
    if (raw.indexOf("de") === 0) {
        return "de"
    }
    if (raw.indexOf("it") === 0) {
        return "it"
    }
    if (raw.indexOf("fr") === 0) {
        return "fr"
    }
    return "en"
}

function catalog(languageCode) {
    var lang = language(languageCode)
    if (lang === "de") {
        return DE
    }
    if (lang === "it") {
        return IT
    }
    if (lang === "fr") {
        return FR
    }
    return EN
}

function weatherCatalog(languageCode) {
    var lang = language(languageCode)
    if (lang === "de") {
        return WEATHER_DE
    }
    if (lang === "it") {
        return WEATHER_IT
    }
    if (lang === "fr") {
        return WEATHER_FR
    }
    return WEATHER_EN
}

