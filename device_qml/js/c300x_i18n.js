function language(languageCode) {
    var raw = String(languageCode || "en").toLowerCase()
    if (raw.indexOf("de") === 0) {
        return "de"
    }
    if (raw.indexOf("it") === 0) {
        return "it"
    }
    if (raw.indexOf("fr") === 0) {
        return "fr"
    }
    if (raw.indexOf("es") === 0) {
        return "es"
    }
    return "en"
}

function catalog(languageCode) {
    var lang = language(languageCode)
    if (lang === "de") {
        return DE
    }
    if (lang === "it") {
        return IT
    }
    if (lang === "fr") {
        return FR
    }
    if (lang === "es") {
        return ES
    }
    return EN
}

