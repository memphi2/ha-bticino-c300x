function language(languageCode) {
    var raw = String(languageCode || "en").toLowerCase()
    if (raw.indexOf("de") === 0) {
        return "de"
    }
    if (raw.indexOf("it") === 0) {
        return "it"
    }
    if (raw.indexOf("fr") === 0) {
        return "fr"
    }
    return "en"
}

function catalog(languageCode) {
    var lang = language(languageCode)
    if (lang === "de") {
        return DE
    }
    if (lang === "it") {
        return IT
    }
    if (lang === "fr") {
        return FR
    }
    return EN
}

function weatherCatalog(languageCode) {
    var lang = language(languageCode)
    if (lang === "de") {
        return WEATHER_DE
    }
    if (lang === "it") {
        return WEATHER_IT
    }
    if (lang === "fr") {
        return WEATHER_FR
    }
    return WEATHER_EN
}

function text(languageCode, key) {
    var local = catalog(languageCode)
    if (local[key]) {
        return local[key]
    }
    if (EN[key]) {
        return EN[key]
    }
    return key
}

function weather(languageCode, key, fallback) {
    var local = weatherCatalog(languageCode)
    var raw = String(key || "unknown").toLowerCase()
    if (local[raw]) {
        return local[raw]
    }
    if (WEATHER_EN[raw]) {
        return WEATHER_EN[raw]
    }
    return fallback || text(languageCode, "unknown")
}
